package com.vera.pinkvoice.audio

import kotlin.math.log2

/**
 * 目标元音 —— **普通话单元音**。
 *
 * ## 参考值从哪来
 *
 * **吴宗济（1960，《声学学报》）：普通话元音的共振峰频率表**。
 *
 * 为什么不用英语的 Peterson & Barney (1952)：
 *
 * 1. **母语不同，元音空间就不同。** P&B 是英语元音，
 *    里面的 /æ/ /ʌ/ 在普通话里根本不是独立单元音。
 *    拿英语的元音位置当普通话的发音目标，本身就错位。
 * 2. **吴宗济表里有男/女配对。** 这让「女性化」可以用**实测的男女比值**，
 *    而不是借用英语文献里的全局常数。
 *
 * ## 男 → 女的比值是逐元音的
 *
 * 吴宗济表里每个元音都有男性和女性两组数据，比值**因元音而异**：
 *
 * | 元音 | F1 比值 | F2 比值 |
 * |---|---|---|
 * | 啊 [a] | 1000/770 = **1.299** | 1300/1100 = **1.182** |
 * | 鹅 [ɤ] | 700/550 = **1.273** | 1300/1100 = **1.182** |
 * | 衣 [i] | 350/310 = **1.129** | 2600/2100 = **1.238** |
 * | 乌 [u] | 480/400 = **1.200** | （吴表无数据，见下） |
 * | 鱼 [y] | 330/260 = **1.269** | 2400/2000 = **1.200** |
 * | 哦 [o] | 700/550 = **1.273** | 1100/850 = **1.294** |
 *
 * 之前用的是全局常数（F1 ×1.18 / F2 ×1.17，源自 Fant 1966、
 * Hillenbrand & Clark 2009 的英语数据）。逐元音的比值更准：
 *
 * - 衣 [i] 的 F1 只抬 1.129 倍 —— 舌位已经很高，抬不动；
 * - 啊 [a] 的 F1 抬 1.299 倍 —— 开口度可以大幅收小。
 *
 * 这正是「保持元音可辨认的前提下整体往前、往上抬」该有的样子：
 * 各个方向能抬多少，由元音本身的解剖结构决定。
 *
 * ## 乌 [u] 的 F2 是怎么来的
 *
 * 吴宗济表里 [u] 的 F2 是空的 —— [u] 的 F1 和 F2 靠得很近，
 * 常规 LPC 分不开，文献里通常不报。
 *
 * - **参考值**用 Peterson & Barney 的 /u/ F2 = 870 Hz（英语和中文的 [u]
 *   在这一项上差别不大）
 * - **比值**用其余五个元音 F2 比值的平均 = 1.22
 *
 * 两处都在代码里标了出处。
 *
 * ## 坐标是什么
 *
 * F1/F2 是**原始频率**（Hz），不做声道长度归一化。
 * 归一换算（折算到 17.5 cm 参考声道）是跨人对比的**科研工具**，
 * 不是初学者能理解的训练目标 —— 见 [VowelRecognizer] 的说明。
 */
enum class VowelTarget(
    /** 显示名。 */
    val label: String,
    /** 参考位置 F1（Hz）—— 吴宗济普通话男性值。 */
    val f1: Float,
    /** 参考位置 F2（Hz）—— 吴宗济普通话男性值。 */
    val f2: Float,
    /**
     * 女性化的 F1 系数（吴宗济女性值 ÷ 男性值）。
     *
     * 「往上抬」—— 开口度变小、舌位抬高。
     */
    val femaleF1Ratio: Float,
    /**
     * 女性化的 F2 系数（吴宗济女性值 ÷ 男性值）。
     *
     * 「往前移」—— 舌位更靠前。
     */
    val femaleF2Ratio: Float,
    /**
     * 这个元音在元音图上的说明（给用户看的一句话）。
     */
    val note: String = "",
) {
    /** 啊 [a] —— 嘴张最大的那个。 */
    A("啊", 770f, 1100f, 1.299f, 1.182f, "嘴张最大的那个音"),

    /** 鹅 [ɤ] —— 介于啊和衣之间。 */
    E("鹅", 550f, 1100f, 1.273f, 1.182f, "半开、舌位居中"),

    /** 衣 [i] —— 舌位最高最前。 */
    I("衣", 310f, 2100f, 1.129f, 1.238f, "舌位最高最前"),

    /** 乌 [u] —— 舌位最高最后，圆唇。 */
    U("乌", 400f, 870f, 1.200f, 1.220f, "圆唇、舌位最后"),

    /** 鱼 [y] —— 唇音化的 [i]，MTF 的黄金元音。 */
    Y("鱼", 260f, 2000f, 1.269f, 1.200f, "圆唇的衣，最容易做出效果"),

    /** 哦 [o] —— 半开、圆唇、舌位最后。 */
    O("哦", 550f, 850f, 1.273f, 1.294f, "圆唇、舌位靠后"),
    ;

    /**
     * 女性化目标位置：F1（Hz）。
     *
     * = 参考位置 × 该元音自己的男→女比值。
     */
    val femaleF1: Float get() = f1 * femaleF1Ratio

    /**
     * 女性化目标位置：F2（Hz）。
     */
    val femaleF2: Float get() = f2 * femaleF2Ratio

    /** 在元音图上的位置（F1 越低越高、F2 越低越靠前）。 */
    val x: Float get() = f2
    val y: Float get() = f1
}

/**
 * 元音识别。
 *
 * 用 F1/F2 和**目标元音**比距离，取最近的。
 *
 * ## 用的是原始频率，不做声道归一化
 *
 * 之前这里做过归一化（折算到 17.5 cm 参考声道）——
 * 那是跨人对比的**科研工具**，对训练没有帮助：
 * 用户看不懂那个换算，也不知道该拿它怎么办。
 *
 * 而且它会把「天生的声道差异」也消掉 ——
 * 但那恰恰是「听起来像不像女性」的一部分。
 * 目标区域应该拿**原始频率**去比。
 *
 * ## 身份和女性化是纠缠的 —— 怎么处理的
 *
 * 元音**身份**（「你在发哪个音」）和**女性化程度**（「离目标还有多远」）
 * 在 F1/F2 平面上是**纠缠**的：女性化目标就在元音位置的前面，
 * 声音往前挪之后，识别标签会跟着漂。
 *
 * 普通话单元音挤得比英语紧，问题更明显。实测「在女性化目标位置
 * 会被认成谁」：
 *
 * | 识别参照 | 啊 | 鹅 | 衣 | 乌 | 鱼 | 哦 |
 * |---|---|---|---|---|---|---|
 * | 只比男性参考位置 | ✓ | ✗ | ✓ | ✗ | ✗ | ✗ |
 * | **男性 + 女性都参与** | ✓ | ✓ | ✓ | ✓ | ✓ | ✓ |
 *
 * 做法是**两个参考点都参与**，但女性化目标点要额外付 90 Hz 的代价
 * （[GOAL_MATCH_PENALTY]）：
 *
 * - 读数靠近某个元音的**女性化目标** → 可以认它（但要更近才行）
 * - 否则按**自然位置**（吴宗济男性值）认
 *
 * 「两个点取更近的」会坏事：女性化目标点落在元音空间中间，
 * 会把本该属于别人的读数吸过来 —— 实测鹅被认成乌、衣被认成鱼，
 * 真实录音的帧正确率从 65% 掉到 36%。
 *
 * 加了代价之后：目标位置 6/6 全对，而自然位置上的识别
 * **一点没变差**（稳定段帧正确率 76.3%，和只比自然点完全一样）。
 *
 * 试过、但更差的另一种改法：
 *
 * **识别时允许整体缩放**（对应「声道长短」的差异）——
 * 衣和鱼的比例太像（0.148 vs 0.130），分不开。
 *
 * 根因是元音图本身的局限：「啊」和「哦」的区别主要在圆唇
 * （影响 F3 和频谱倾斜），不在 F1/F2 上。
 * 只靠 F1/F2 分不出这两个 —— 这是元音图的天花板，
 * 不是实现能绕过去的。
 */
object VowelRecognizer {

    /** 识别结果。 */
    data class Result(
        /** 识别出的元音；null 表示哪个都不像。 */
        val vowel: VowelTarget?,
        /** 与目标元音的距离（Hz 的欧氏距离）。 */
        val distance: Float,
    ) {
        /** 是否够接近（可以认为"就是它"）。 */
        val confident: Boolean get() = vowel != null && distance <= CONFIDENT_DISTANCE
    }

    /**
     * 判定"就是这个元音"的距离阈值。
     *
     * Hz 空间里的欧氏距离。实测合成元音的误差在 40–80 Hz，
     * 取 180 作为"认得出"的界。
     */
    const val CONFIDENT_DISTANCE = 180f

    /**
     * 识别一个元音。
     *
     * @param f1 原始 F1（Hz）
     * @param f2 原始 F2（Hz）
     */
    fun recognize(f1: Float, f2: Float): Result {
        if (f1 <= 0f || f2 <= 0f) return Result(null, Float.MAX_VALUE)
        var best: VowelTarget? = null
        var bestDist = Float.MAX_VALUE
        for (v in VowelTarget.entries) {
            val d = distanceTo(v, f1, f2)
            if (d < bestDist) {
                bestDist = d
                best = v
            }
        }
        return Result(best, bestDist)
    }

    /**
     * 女性化目标位置的**劣势**（Hz）。
     *
     * 目标点比自然点「难赢」这么多 —— 也就是目标点要多近 90 Hz
     * 才抢得走自然点。
     *
     * ## 为什么要有这个劣势
     *
     * 女性化目标落在元音空间中间，不加限制的话会抢走本该属于
     * 别人的读数：
     *
     * - 典型男性 /啊/（约 730/1090）离「哦的女性化目标」（700/1100）
     *   只有 43 Hz，离「啊的自然位置」（770/1100）只有 57 Hz ——
     *   不加限制就会被判成「哦」。
     *
     * 加了 90 Hz 的劣势之后（实测）：
     *
     * | | 在目标位置认对 | 真实录音稳定段帧正确率 | 典型男性 /啊/ |
     * |---|---|---|---|
     * | 只比自然位置 | 2/6 | 76.3% | ✓ |
     * | **加 90 Hz 劣势** | **6/6** | **76.3%** | ✓ |
     *
     * 目标位置全认对，而自然位置上的识别**一点没变差**。
     */
    const val GOAL_MATCH_PENALTY = 90f

    /**
     * 到目标元音的距离（越小越像）。
     *
     * **两个参考点都参与**：自然位置（吴宗济男性值）和
     * 女性化目标位置。目标点要额外付 [GOAL_MATCH_PENALTY] 的代价 ——
     * 详见本文件开头的说明。
     */
    fun distanceTo(target: VowelTarget, f1: Float, f2: Float): Float {
        if (f1 <= 0f || f2 <= 0f) return Float.MAX_VALUE
        val dNatural = pointDistance(f1, f2, target.f1, target.f2)
        val dGoal = pointDistance(f1, f2, target.femaleF1, target.femaleF2) + GOAL_MATCH_PENALTY
        return minOf(dNatural, dGoal)
    }

    /**
     * 到一个参考点的距离。
     *
     * F2 的差异对"听起来像不像"影响更大（舌位变化更明显），
     * 所以给它 1.4 倍权重。
     */
    private fun pointDistance(f1: Float, f2: Float, refF1: Float, refF2: Float): Float {
        val dx = f2 - refF2
        val dy = (f1 - refF1) * 1.4f
        return kotlin.math.sqrt(dx * dx + dy * dy)
    }
}
